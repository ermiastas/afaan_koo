import 'dart:ui';

class DoubleLetter {

  final String letter;

  final String pronunciation;

  final String emoji;

  final String image;

  final List<String> words;

  final String audio;

  final Color color;

  const DoubleLetter({

    required this.letter,

    required this.pronunciation,

    required this.emoji,

    required this.image,

    required this.words,

    required this.audio,

    required this.color,

  });

}